@router.get("/seeddata/presets")
def get_presets():
    return {"presets": [
        {"id": p["id"], "bucket": p["bucket"], "description": p["description"],
         "object_count": len(p["objects"])}
        for p in BUCKET_PRESETS
    ]}


class GenerateRequest(BaseModel):
    tenant:     str
    preset_ids: List[str]   # which bucket presets to create; empty = all


class CleanupRequest(BaseModel):
    tenant:  str
    buckets: List[str]      # bucket names to delete


@router.post("/seeddata/generate")
def generate_sample_data(req: GenerateRequest):
    """Create selected buckets and upload sample objects. Streams SSE progress."""

    selected = [p for p in BUCKET_PRESETS if not req.preset_ids or p["id"] in req.preset_ids]

    def _sse(step, status, message, **extra):
        """Build an SSE data line without backslashes inside f-strings."""
        payload = {"step": step, "status": status, "message": message}
        payload.update(extra)
        return "data: " + json.dumps(payload) + "\n\n"

    def _stream():
        s3 = get_s3_client(req.tenant)
        created_buckets = []
        total_objects   = 0
        total_errors    = 0

        init_msg = "Starting load generator for tenant " + req.tenant + " — " + str(len(selected)) + " bucket(s) to create"
        yield _sse("init", "running", init_msg)
        time.sleep(0.3)

        for preset in selected:
            bname = preset["bucket"]

            # Create bucket
            yield _sse("bucket", "running", "Creating bucket " + bname + "…")
            try:
                try:
                    s3.create_bucket(Bucket=bname)
                except ClientError as e:
                    if e.response['Error']['Code'] in ('BucketAlreadyExists', 'BucketAlreadyOwnedByYou'):
                        pass  # already exists — still upload objects
                    else:
                        raise
                created_buckets.append(bname)
                yield _sse("bucket", "success", "Bucket " + bname + " ready")
            except Exception as e:
                yield _sse("bucket", "failed", "Bucket " + bname + " failed: " + str(e))
                total_errors += 1
                continue

            # Upload objects
            for fname, ftype in preset["objects"]:
                yield _sse("upload", "running", "  Uploading " + fname + "…")
                try:
                    content, ctype = _make_content(fname, ftype)
                    s3.put_object(
                        Bucket=bname,
                        Key=fname,
                        Body=io.BytesIO(content),
                        ContentType=ctype,
                        Metadata={GENERATOR_TAG_KEY: GENERATOR_TAG_VALUE},
                    )
                    total_objects += 1
                    size_kb = round(len(content) / 1024, 1)
                    ext = ctype.split("/")[1] if "/" in ctype else ctype
                    yield _sse("upload", "success", "  " + fname + " (" + str(size_kb) + " KB, " + ext + ")")
                except Exception as e:
                    yield _sse("upload", "failed", "  " + fname + " failed: " + str(e))
                    total_errors += 1
                time.sleep(0.1)

        summary = "Done — " + str(len(created_buckets)) + " bucket(s), " + str(total_objects) + " objects uploaded"
        if total_errors:
            summary += ", " + str(total_errors) + " error(s)"
        final_status = "success" if not total_errors else "warning"
        yield _sse("done", final_status, summary, buckets=created_buckets, object_count=total_objects)

    return StreamingResponse(_stream(), media_type="text/event-stream",
                             headers={"Cache-Control": "no-cache", "X-Accel-Buffering": "no"})


@router.post("/seeddata/cleanup")
def cleanup_sample_data(req: CleanupRequest):
    """Delete all objects and buckets that were created by the load generator."""
    s3 = get_s3_client(req.tenant)
    results = []

    for bname in req.buckets:
        bucket_result = {"bucket": bname, "objects_deleted": 0, "error": None}
        try:
            # List and delete all objects first
            paginator = s3.get_paginator("list_objects_v2")
            for page in paginator.paginate(Bucket=bname):
                objects = [{"Key": o["Key"]} for o in page.get("Contents", [])]
                if objects:
                    s3.delete_objects(Bucket=bname, Delete={"Objects": objects})
                    bucket_result["objects_deleted"] += len(objects)
            # Delete the bucket
            s3.delete_bucket(Bucket=bname)
            bucket_result["status"] = "deleted"
        except ClientError as e:
            bucket_result["status"] = "error"
            bucket_result["error"]  = e.response["Error"]["Code"]
        except Exception as e:
            bucket_result["status"] = "error"
            bucket_result["error"]  = str(e)
        results.append(bucket_result)

    total_deleted = sum(r["objects_deleted"] for r in results)
    errors        = [r for r in results if r["status"] == "error"]
    return {
        "results":       results,
        "buckets_cleaned": len([r for r in results if r["status"] == "deleted"]),
        "objects_deleted": total_deleted,
        "errors":          len(errors),
    }
