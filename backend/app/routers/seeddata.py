def _csv(name: str) -> bytes:
    rows = ["timestamp,tenant,bucket,operation,bytes,latency_ms,status"]
    import random, datetime
    base = datetime.datetime(2026, 9, 1, 0, 0, 0)
    for i in range(50):
        ts  = (base + datetime.timedelta(hours=i*3)).isoformat()
        ops = random.choice(["PutObject","GetObject","DeleteObject","ListObjects"])
        byt = random.randint(1024, 10_485_760)
        lat = random.randint(2, 250)
        sta = random.choice(["200","200","200","403","404"])
        rows.append(f"{ts},{name},{name}-bucket,{ops},{byt},{lat},{sta}")
    return "\n".join(rows).encode()


