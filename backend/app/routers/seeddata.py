GENERATOR_TAG_KEY   = "x-amz-meta-generated-by"
GENERATOR_TAG_VALUE = "infinia-load-generator"


def _make_content(fname: str, ftype: str) -> tuple:
    """Return (bytes, content_type) for a given file."""
    stem = fname.replace("-", " ").replace("_", " ").title()
    if ftype == "pdf":
        return _pdf(stem), "application/pdf"
    elif ftype == "docx":
        return _docx_stub(stem), "application/vnd.openxmlformats-officedocument.wordprocessingml.document"
    elif ftype == "csv":
        return _csv(stem), "text/csv"
    else:
        return _txt(fname, stem), "text/plain"


